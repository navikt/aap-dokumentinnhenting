CREATE TABLE DIALOGMELDING_STATUS_HISTORIKK
(
    ID                   BIGSERIAL PRIMARY KEY,
    DIALOGMELDING_UUID    UUID NOT NULL REFERENCES DIALOGMELDING (DIALOGMELDING_UUID),
    KILDEHENDELSE_ID      TEXT NOT NULL UNIQUE,
    STATUS               TEXT NOT NULL,
    TEKST                TEXT,
    HENDELSE_TIDSPUNKT    TIMESTAMP WITH TIME ZONE NOT NULL,
    MOTTATT_TIDSPUNKT     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IDX_DIALOGMELDING_STATUS_HISTORIKK_DIALOGMELDING_UUID
    ON DIALOGMELDING_STATUS_HISTORIKK (DIALOGMELDING_UUID);
