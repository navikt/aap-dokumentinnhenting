CREATE TABLE PAAMINNELSE
(
    ID                   BIGSERIAL    NOT NULL PRIMARY KEY,
    DIALOGMELDING_UUID   UUID         NOT NULL REFERENCES DIALOGMELDING (DIALOGMELDING_UUID),
    BEHANDLINGSREFERANSE UUID         NOT NULL,
    STATUS               TEXT         NOT NULL,
    PAMINNELSESDATO      DATE         NOT NULL,
    OPPRETTET_TIDSPUNKT  TIMESTAMP(3) NOT NULL
);

CREATE INDEX IDX_PAAMINNELSE_DIALOGMELDING_UUID ON PAAMINNELSE (DIALOGMELDING_UUID);
CREATE INDEX IDX_PAAMINNELSE_BEHANDLINGSREFERANSE ON PAAMINNELSE (BEHANDLINGSREFERANSE);
CREATE INDEX IDX_PAAMINNELSE_PAAMINNELSESDATO ON PAAMINNELSE (PAMINNELSESDATO);